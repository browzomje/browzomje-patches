#!/usr/bin/env python3
"""Validate or generate the Pinterest extension catalog without Gradle or network access."""
import argparse
from collections import Counter
import json
from pathlib import Path
import re
import subprocess
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
CATALOG = Path("extensions/extension/src/main/l10n")
JAVA = Path("extensions/extension/src/main/java/app/template/extension/pinterest")
PLACEHOLDER = re.compile(r"%(?:\d+\$[a-zA-Z]|[a-zA-Z]|\d+|%)")
PROTECTED = ("adb logcat -s Morphe:V", "yt-dlp", "MP4/HLS/DASH", "HLS/DASH", "pin.it")
ANDROID_NAME = "{http://schemas.android.com/apk/res/android}name"


def unique_object(entries):
    result = {}
    for key, value in entries:
        if key in result:
            raise ValueError(f"duplicate JSON key {key}")
        result[key] = value
    return result


def read_json(read, path):
    try:
        result = json.loads(read(path), object_pairs_hook=unique_object)
        if not isinstance(result, dict):
            raise ValueError("expected a JSON object")
        return result
    except ValueError as error:
        raise ValueError(f"{path.name}: {error}") from error


def load_catalog(read, source_paths, locale_config=None):
    locale_map = read_json(read, CATALOG / "locale-map.json")
    if locale_config:
        declared = {item.attrib[ANDROID_NAME] for item in ET.parse(locale_config).iter("locale")}
        if declared != locale_map.keys():
            raise ValueError(f"locale inventory differs: missing {sorted(declared - locale_map.keys())}, "
                             f"obsolete {sorted(locale_map.keys() - declared)}")
    if any(not isinstance(tag, str) or not re.fullmatch(r"[a-z]{2,3}(?:-[A-Z]{2})?", tag)
           for tag in locale_map.values()):
        raise ValueError("invalid translation table name")
    english = read_json(read, CATALOG / "en.json")
    required = set(re.findall(r'\bstatic final String \w+ = "([a-z0-9_]+)";', read(JAVA / "MorpheStrings.java")))
    qualified_key = r'\b(?:PinterestUtils\.(?:getString|getLocalizedError)|MorpheStrings\.(?:get|find))\("([a-z0-9_]+)"\)'
    for path in source_paths:
        required.update(re.findall(qualified_key, read(path)))
    utils = read(JAVA / "PinterestUtils.java")
    required.update(re.findall(r'(?<![.\w])getString\("([a-z0-9_]+)"\)', utils))
    if not english or required - english.keys():
        raise ValueError(f"English catalog is missing UI keys: {sorted(required - english.keys())}")
    tables = {}
    errors = []
    for lang in sorted(set(locale_map.values())):
        rows = read_json(read, CATALOG / f"{lang}.json")
        for key in sorted(english.keys() - rows.keys()):
            errors.append(f"{lang}/{key}: missing")
        for key in sorted(rows.keys() - english.keys()):
            errors.append(f"{lang}/{key}: unknown key")
        for key in sorted(rows.keys() & english.keys()):
            text, original = rows[key], english[key]
            if not isinstance(text, str) or not text.strip():
                errors.append(f"{lang}/{key}: blank or non-string")
                continue
            if not isinstance(original, str):
                errors.append(f"en/{key}: non-string")
                continue
            if Counter(PLACEHOLDER.findall(text)) != Counter(PLACEHOLDER.findall(original)):
                errors.append(f"{lang}/{key}: format placeholders differ")
            if any(token in original and token not in text for token in PROTECTED):
                errors.append(f"{lang}/{key}: technical term changed")
            if original.endswith(" ") != text.endswith(" "):
                errors.append(f"{lang}/{key}: trailing space differs")
        tables[lang] = rows
    if errors:
        raise ValueError("\n".join(errors))
    return locale_map, tables


def render(locale_map, tables):
    def quote(text):
        return json.dumps(text, ensure_ascii=False)

    keys = sorted(tables["en"])
    lines = [
        "// Generated by scripts/pinterest_l10n.py.",
        "package app.browzomje.extension.pinterest;",
        "",
        "final class PinterestStringCatalog {",
        "    private PinterestStringCatalog() {}",
        "    static final String[] KEYS = {" + ", ".join(map(quote, keys)) + "};",
        "    static final String[] LANGUAGES = {" + ", ".join(map(quote, tables)) + "};",
        "    static String resolve(String tag, String base) {",
        "        String exact = mapped(tag);",
        "        if (exact != null) return exact;",
        "        String language = mapped(base);",
        '        return language == null ? "en" : language;',
        "    }",
        "    private static String mapped(String tag) {",
        "        switch (tag) {",
    ]
    aliases = {tag.replace("-r", "-"): lang for tag, lang in locale_map.items()}
    aliases.update({lang: lang for lang in tables})
    aliases.update({"uk": "uk", "no": "nb"})
    for tag, lang in sorted(aliases.items()):
        lines.append(f"            case {quote(tag)}: return {quote(lang)};")
    lines.extend((
        "            default: return null;",
        "        }",
        "    }",
        "    static String[] forLanguage(String language) {",
        "        switch (language) {",
    ))
    for lang in tables:
        lines.append(f"            case {quote(lang)}: return Table_{lang.replace('-', '_')}.VALUES;")
    lines.extend(("            default: return Table_en.VALUES;", "        }", "    }"))
    for lang, rows in tables.items():
        lines.append(f"    private static final class Table_{lang.replace('-', '_')} {{")
        lines.append("        private static final String[] VALUES = {")
        lines.extend(f"            {quote(rows[key])}," for key in keys)
        lines.extend(("        };", "    }"))
    return "\n".join([*lines, "}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--locale-config", type=Path, help="compare with an original APK's decoded locales_config.xml")
    parser.add_argument("--output", type=Path, help="generate Java into this source directory")
    parser.add_argument("--index", action="store_true", help="check the staged snapshot instead of the working tree")
    args = parser.parse_args()

    def read(path):
        if args.index:
            result = subprocess.run(["git", "show", f":{path.as_posix()}"], cwd=ROOT,
                                    capture_output=True, encoding="utf-8")
            if result.returncode:
                raise ValueError(f"{path.name}: missing from staged snapshot")
            return result.stdout
        return (ROOT / path).read_text(encoding="utf-8")

    try:
        if args.index:
            staged = subprocess.check_output(["git", "ls-files", "-z", "--cached", "--", JAVA.as_posix()],
                                             cwd=ROOT, encoding="utf-8")
            paths = [Path(path) for path in staged.split("\0") if path.endswith(".java")]
        else:
            paths = [path.relative_to(ROOT) for path in (ROOT / JAVA).glob("*.java")]
        locales, tables = load_catalog(read, paths, args.locale_config)
        if args.output:
            destination = args.output / "app/browzomje/extension/pinterest/PinterestStringCatalog.java"
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(render(locales, tables), encoding="utf-8")
    except (OSError, ValueError, ET.ParseError) as error:
        print(f"FAIL Pinterest localization: {error}", file=sys.stderr)
        return 1
    print(f"PASS Pinterest localization: {len(tables['en'])} strings, {len(tables)} tables, {len(locales)} locale tags")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
